// Helper to calculate Tanzanian PAYE brackets
export function calculatePAYE(taxableIncome: number): number {
  if (taxableIncome <= 270000) return 0;
  if (taxableIncome <= 520000) return (taxableIncome - 270000) * 0.08;
  if (taxableIncome <= 760000) return 20000 + (taxableIncome - 520000) * 0.20;
  if (taxableIncome <= 1000000) return 68000 + (taxableIncome - 760000) * 0.25;
  return 128000 + (taxableIncome - 1000000) * 0.30;
}

export function generateMonthlyPayroll(employees: Employee[], monthName: string = 'Novemba 2026'): PayrollRun {
  const records = employees.map((emp, index) => {
    const totalAllowances = Object.values(emp.allowances).reduce((a, b) => a + b, 0);
    const overtimeHours = index % 2 === 0 ? 5 : 0;
    const hourlyRate = emp.basicSalary / 160;
    const overtimePay = Math.round(overtimeHours * hourlyRate * 1.5);
    const grossSalary = emp.basicSalary + totalAllowances + overtimePay;

    const nssf = Math.round(emp.basicSalary * 0.10); // 10%
    const taxableIncome = grossSalary - nssf;
    const paye = Math.round(calculatePAYE(taxableIncome));
    const wcf = Math.round(emp.basicSalary * 0.01); // 1%
    const nhif = 50000; // Flat or rate
    const heslb = emp.employeeNo === 'KD-2024-031' ? Math.round(emp.basicSalary * 0.15) : 0;
    const salaryAdvance = index === 3 ? 200000 : 0;
    const otherDeductions = 0;

    const totalDeductions = nssf + paye + wcf + nhif + heslb + salaryAdvance + otherDeductions;
    const netSalary = grossSalary - totalDeductions;

    return {
      id: `PAY-REC-${emp.id}`,
      employeeId: emp.id,
      employeeNo: emp.employeeNo,
      employeeName: emp.fullName,
      roleTitle: emp.roleTitle,
      department: emp.department,
      bankName: emp.bankName,
      accountNumber: emp.accountNumber,
      basicSalary: emp.basicSalary,
      allowances: { ...emp.allowances },
      totalAllowances,
      overtimeHours,
      overtimePay,
      grossSalary,
      deductions: {
        nssf,
        paye,
        wcf,
        nhif,
        heslb,
        salaryAdvance,
        otherDeductions,
      },
      totalDeductions,
      netSalary,
      paymentStatus: 'paid' as const,
      payslipRef: `SLIP/2026-11/${(100 + index)}`,
    };
  });

  const totalGross = records.reduce((sum, r) => sum + r.grossSalary, 0);
  const totalDeductions = records.reduce((sum, r) => sum + r.totalDeductions, 0);
  const totalNet = records.reduce((sum, r) => sum + r.netSalary, 0);

  return {
    id: 'PR-2026-11',
    month: monthName,
    periodCode: '2026-11',
    status: 'approved',
    createdAt: '2026-11-01',
    disbursedDate: '2026-11-02',
    approvedBy: 'Mhandisi Juma Bakari',
    totalEmployees: records.length,
    totalGross,
    totalDeductions,
    totalNet,
    records,
  };
}

